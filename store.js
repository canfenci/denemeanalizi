export function getKonuListesiBySinif(sinif) {
    const normalized = String(sinif || "").trim();
    const branches = store.teacherBranches || ["Türkçe", "Matematik", "Fen Bilimleri", "Sosyal Bilgiler"];
    const hasMath = branches.includes("Matematik");
    const hasScience = branches.includes("Fen Bilimleri");
    const hasTurkish = branches.includes("Türkçe");
    const hasSocial = branches.includes("Sosyal Bilgiler");

    let list = [];
    if (normalized === "5") {
        if (hasTurkish) list = list.concat(KONU_LISTESI_SINIF5_TUR);
        if (hasMath) list = list.concat(KONU_LISTESI_SINIF5_MAT);
        if (hasScience) list = list.concat(KONU_LISTESI_SINIF5_FEN);
        if (hasSocial) list = list.concat(KONU_LISTESI_SINIF5_SOS);
    } else if (normalized === "6") {
        if (hasTurkish) list = list.concat(KONU_LISTESI_SINIF6_TUR);
        if (hasMath) list = list.concat(KONU_LISTESI_SINIF6_MAT);
        if (hasScience) list = list.concat(KONU_LISTESI_SINIF6_FEN);
        if (hasSocial) list = list.concat(KONU_LISTESI_SINIF6_SOS);
    } else if (normalized === "7") {
        if (hasTurkish) list = list.concat(KONU_LISTESI_SINIF7_TUR);
        if (hasMath) list = list.concat(KONU_LISTESI_SINIF7_MAT);
        if (hasScience) list = list.concat(KONU_LISTESI_SINIF7_FEN);
        if (hasSocial) list = list.concat(KONU_LISTESI_SINIF7_SOS);
    } else { // LGS
        if (hasTurkish) list = list.concat(KONU_LISTESI_LGS_TUR);
        if (hasMath) list = list.concat(KONU_LISTESI_LGS_MAT);
        if (hasScience) list = list.concat(KONU_LISTESI_LGS_FEN);
        if (hasSocial) list = list.concat(KONU_LISTESI_LGS_SOS);
    }

    if (list.length === 0) {
        return ["Branş Seçimi Yapılmadı"];
    }
    return list;
}

