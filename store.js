export function loadGroupsData() {
    if (store.useFirestore && window.isFirebaseActive) {
        return store.globalGroups || [];
    }
    try {
        const raw = localStorage.getItem(localDataKey(GROUPS_KEY));
        return raw ? JSON.parse(raw) : [];
    } catch (e) {
        console.error("loadGroupsData error", e);
        return [];
    }
}

export function saveGroupsData(groups) {
    store.globalGroups = groups;
    if (store.useFirestore && window.isFirebaseActive && window.db) {
        const user = window.auth?.currentUser;
        const userId = user ? user.uid : null;
        groups.forEach(g => {
            const docData = { ...g };
            if (userId) docData.userId = userId;
            window.db.collection("groups").doc(g.id).set(docData).catch(err => {
                console.error(err);
                if (window.handleFirebaseError) window.handleFirebaseError(err);
            });
        });
        if (window.showSyncStatus) window.showSyncStatus("✅ Bulut senkronize edildi", false);
    } else {
        try {
            localStorage.setItem(localDataKey(GROUPS_KEY), JSON.stringify(groups));
            if (window.showSyncStatus) window.showSyncStatus("✅ Kaydedildi", false);
        } catch (e) {
            console.error("saveGroupsData error", e);
        }
    }
}

export function deleteGroupData(groupId) {
    store.globalGroups = store.globalGroups.filter(g => g.id !== groupId);
    if (store.useFirestore && window.isFirebaseActive && window.db) {
        window.db.collection("groups").doc(groupId).delete().catch(err => {
            console.error(err);
            if (window.handleFirebaseError) window.handleFirebaseError(err);
        });
        if (window.showSyncStatus) window.showSyncStatus("✅ Bulut senkronize edildi", false);
    } else {
        try {
            localStorage.setItem(localDataKey(GROUPS_KEY), JSON.stringify(store.globalGroups));
            if (window.showSyncStatus) window.showSyncStatus("✅ Kaydedildi", false);
        } catch (e) {
            console.error("deleteGroupData error", e);
        }
    }
}

